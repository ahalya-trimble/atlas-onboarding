#!/usr/bin/env python3
"""Build explorer/js/data.js from the two files people edit.

  curriculum.json        the topic list the ATLAS Tutor agent labels questions with (ids, order, sources,
                         objectives, prerequisites, starter questions)
  content/lessons.json   how the Explorer presents it (hook, key points, diagrams, quiz, videos)

data.js is GENERATED. Do not edit it by hand. Everything the two sides share (lesson ids, source
documents and sections, objectives, starter questions, prerequisites) is
copied from curriculum.json, so the agent and the Explorer cannot drift apart.

  python scripts/build_explorer.py           write explorer/js/data.js
  python scripts/build_explorer.py --check   fail if data.js is stale or the two files disagree
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CURRICULUM = ROOT / "curriculum.json"
CONTENT = ROOT / "content" / "lessons.json"
OUT = ROOT / "explorer" / "js" / "data.js"
HEADER = ("/* GENERATED by scripts/build_explorer.py from curriculum.json and content/lessons.json.\n"
          "   Do not edit by hand: edit those two files and run the script. */\n")


def uniq(items):
    seen, out = set(), []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def build():
    cur = json.loads(CURRICULUM.read_text(encoding="utf-8-sig"))
    con = json.loads(CONTENT.read_text(encoding="utf-8-sig"))
    lessons = {item["id"]: item for item in cur["lessons"]}
    errors, covered = [], {}
    for item in con["lessons"]:
        for topic in [item["id"]] + item.get("covers", []):
            if topic not in lessons:
                errors.append(f"Explorer lesson '{item['id']}' uses unknown curriculum id '{topic}'")
            elif topic in covered:
                errors.append(f"Curriculum lesson '{topic}' is covered twice ('{covered[topic]}' and '{item['id']}')")
            else:
                covered[topic] = item["id"]
    for topic in lessons:
        if topic not in covered:
            errors.append(f"Curriculum lesson '{topic}' has no Explorer lesson (add it to content/lessons.json)")
    phase_ids = {p["id"] for p in con["phases"]}
    for module in cur["modules"]:
        phase = con["phaseOfModule"].get(module["id"])
        if phase not in phase_ids:
            errors.append(f"Module '{module['id']}' is not mapped to an Explorer phase")
    if errors:
        return None, errors

    out_lessons = []
    for item in con["lessons"]:
        topics = [item["id"]] + item.get("covers", [])
        parts = [lessons[t] for t in topics]
        src, secs = [], {}
        for part in parts:
            for source in part["sources"]:
                src.append(source["path"])
                secs.setdefault(source["path"], [])
                secs[source["path"]] = uniq(secs[source["path"]] + source.get("sections", []))
        src = uniq(src + item.get("extraSrc", []))
        before = uniq(p for part in parts for p in part["prerequisites"])
        prereq = uniq(covered[p] for p in before if covered[p] != item["id"])
        starters = uniq(part["starterQuestion"] for part in parts)
        prompts = uniq(starters + item.get("prompts", []))[:5]
        lesson = {"id": item["id"], "phase": con["phaseOfModule"][parts[0]["moduleId"]],
                  "module": parts[0]["moduleId"], "topics": topics}
        lesson.update({k: v for k, v in item.items()
                       if k not in ("id", "covers", "extraSrc", "prompts", "phase")})
        lesson.update({
            "src": src, "secs": secs, "prereq": prereq,
            "goals": uniq(g for part in parts for g in part["objectives"]),
            "prompts": prompts})
        out_lessons.append(lesson)
    data = {"videos": con["videos"], "phases": con["phases"], "glossary": con["glossary"],
            "legacyIds": con.get("legacyIds", {}), "lessons": out_lessons}
    return HEADER + "window.ATLAS = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n", []


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, errors = build()
    if errors:
        print("Curriculum and Explorer content are not aligned:", file=sys.stderr)
        for error in errors:
            print(" - " + error, file=sys.stderr)
        return 1
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print("explorer/js/data.js is out of date. Run: python scripts/build_explorer.py", file=sys.stderr)
            return 1
        print("Explorer data is aligned with curriculum.json.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text)//1024} KB).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
